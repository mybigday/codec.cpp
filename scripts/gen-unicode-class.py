#!/usr/bin/env python3
"""Generate src/runtime/unicode_class.cpp.

Classifies every codepoint the way the HF `tokenizers` Whitespace
pre-tokenizer (`\\w+|[^\\w\\s]+`) does, by probing the pre-tokenizer itself,
and writes the `\\w` and `\\s` codepoint ranges as C tables.

    .venv/bin/python scripts/gen-unicode-class.py
"""
import pathlib

from tokenizers import __version__ as tokenizers_version
from tokenizers.pre_tokenizers import Whitespace

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "runtime" / "unicode_class.cpp"


def classify():
    pt = Whitespace()
    cls = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            cls.append("other")
            continue
        pieces = [p for p, _ in pt.pre_tokenize_str("a" + chr(cp) + "a")]
        if pieces == ["a", "a"]:
            cls.append("space")
        elif len(pieces) == 1:
            cls.append("word")
        else:
            cls.append("other")
    return cls


def ranges(cls, kind):
    out, start = [], None
    for cp, c in enumerate(cls + [None]):
        if c == kind and start is None:
            start = cp
        elif c != kind and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def table(name, rs):
    lines = [f"const Range {name}[] = {{"]
    for i in range(0, len(rs), 4):
        lines.append("    " + " ".join(f"{{0x{a:05X}, 0x{b:05X}}}," for a, b in rs[i:i + 4]))
    lines.append("};")
    return "\n".join(lines)


def main():
    cls = classify()
    word, space = ranges(cls, "word"), ranges(cls, "space")
    src = f"""// Generated by scripts/gen-unicode-class.py (tokenizers {tokenizers_version}); do not edit.
//
// Codepoint classes of the HF `tokenizers` Whitespace pre-tokenizer
// (`\\w+|[^\\w\\s]+`).

#include "unicode_class.h"

#include <algorithm>
#include <iterator>

namespace {{

struct Range {{
    uint32_t lo;
    uint32_t hi;
}};

{table("k_word", word)}

{table("k_space", space)}

template <size_t N>
bool in_ranges(const Range (&rs)[N], uint32_t cp) {{
    const Range * it = std::upper_bound(std::begin(rs), std::end(rs), cp,
                                        [](uint32_t v, const Range & r) {{ return v < r.lo; }});
    return it != std::begin(rs) && cp <= (it - 1)->hi;
}}

}} // namespace

bool codec_unicode_is_word(uint32_t cp) {{ return in_ranges(k_word, cp); }}

bool codec_unicode_is_space(uint32_t cp) {{ return in_ranges(k_space, cp); }}
"""
    OUT.write_text(src)
    print(f"{OUT}: {len(word)} word ranges, {len(space)} space ranges")


if __name__ == "__main__":
    main()
